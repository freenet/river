function chip(row: Locator, emoji: string): Locator {
  return row.locator(`[data-testid="reaction-chip"][data-emoji="${emoji}"]`);
}

const owners = (page: Page) => page.getByTestId("reaction-owners");
const count = (target: Locator) => target.getByTestId("reaction-chip-count");
const order = (row: Locator) => chips(row).evaluateAll((els) => els.map((el) => el.getAttribute("data-emoji")));

async function pick(page: Page, row: Locator, emoji: string) {
  await openInlinePicker(page, row);
  await (await reactionChoices(page)).filter({ hasText: new RegExp(`^${emoji}$`, "u") }).click();
  await expect(chip(row, emoji)).toHaveAttribute("aria-pressed", "true");
}

// Native clicks generated by the keyboard and assistive technologies carry
// no pointer press. Synthesizing that boundary is deliberate; mouse/touch
// behavior below uses the browser's actual input sequence.
async function activateWithoutPointer(target: Locator) {
  await target.evaluate((el) => (el as HTMLButtonElement).click());
}

// A mouse button going down on the chip, with nothing after it: no lift, no
// click. What follows it is the test's.
async function mouseDownOnly(target: Locator) {
  await target.dispatchEvent("pointerdown", { pointerType: "mouse", pointerId: 1, isPrimary: true, button: 0 });
}

test.describe("Native reaction chip actions", () => {
  test.beforeEach(async ({ page }) => asTouchTablet(page));

  test("mouse adds, removes and switches with accurate native state and counts", async ({ page }) => {
    const row = await openRoomWithTarget(page);
    await callRiverTest(page, "memberReactsToNewest", "🦀");
    await callRiverTest(page, "memberReactsToNewest", "❤️");
    const crab = chip(row, "🦀");
    const heart = chip(row, "❤️");
    await expect(crab).toHaveJSProperty("tagName", "BUTTON");
    await expect(crab).toHaveAttribute("type", "button");
    await expect(crab).toHaveAttribute("aria-pressed", "false");
    await expect(crab).toHaveAttribute("aria-haspopup", "dialog");
    await expect(count(crab)).toHaveText("1");
    await expect(crab).toHaveAccessibleName("🦀, 1 reaction");
    await crab.click();
    await expect(crab).toHaveAttribute("aria-pressed", "true");
    await expect(count(crab)).toHaveText("2");
    await expect(crab).toHaveAccessibleName("🦀, 2 reactions");
    await expect(owners(page)).toHaveCount(0);
    await heart.click();
    await expect(heart).toHaveAttribute("aria-pressed", "true");
    await expect(count(heart)).toHaveText("2");
    await expect(crab).toHaveAttribute("aria-pressed", "false");
    await expect(count(crab)).toHaveText("1");
    await heart.click();
    await expect(heart).toHaveAttribute("aria-pressed", "false");
    await expect(count(heart)).toHaveText("1");
    await expect(row.getByTestId("message-react-button"), "one picker invoker, distinct from native chips").toHaveCount(1);

    // A direct removal that takes the chip with it keeps focus on the
    // message's reaction line: a surviving chip, else its persistent React.
    // Focus is cleared first, once the pick's own focus return has landed,
    // so only the removal can have put it there (WebKit focuses no button on
    // a mouse click; the others focus the chip that is about to go).
    const clearFocus = async () => {
      await settle(page);
      await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur());
    };
    await pick(page, row, "👍");
    await clearFocus();
    await chip(row, "👍").click();
    await expect(chip(row, "👍")).toHaveCount(0);
    await expect(chips(row), "premise: the other members' chips remain").toHaveCount(2);
    await expect(row.locator('[data-testid="reaction-chip"]:focus'), "focus is on a surviving chip").toHaveCount(1);

    await callRiverTest(page, "appendMessage", "sole reaction");
    const sole = committedRow(page, "sole reaction");
    await pick(page, sole, "👍");
    await expect(chips(sole), "premise: the message's only chip").toHaveCount(1);
    await clearFocus();
    await chip(sole, "👍").click();
    await expect(chips(sole)).toHaveCount(0);
    await expect(sole.getByTestId("message-react-button"), "no chip is left: focus is on React").toBeFocused();
  });

  test("inspection exposes explicit React, Switch and Remove actions", async ({ page }) => {
    const row = await openRoomWithTarget(page);
    await callRiverTest(page, "memberReactsToNewest", "🦀");
    const crab = chip(row, "🦀");
    // Native Enter and Space each send the button one click, which inspects:
    // one list, focused, and nothing toggled.
    const inspectWith = async (key: string) => {
      await crab.press(key);
      await expect(owners(page), `${key}: one list`).toHaveCount(1);
      await expect(owners(page)).toBeFocused();
      await expect(crab).toHaveAttribute("aria-expanded", "true");
      await expect(crab).toHaveAttribute("aria-controls", await owners(page).getAttribute("id") as string);
      await expect(crab, `${key}: inspection does not react`).toHaveAttribute("aria-pressed", "false");
      await expect(count(crab)).toHaveText("1");
      await expect(owners(page).getByTestId("reaction-owner")).toHaveText("Test Sender B");
      await expect(owners(page).getByTestId("reaction-apply")).toHaveText("React with 🦀");
    };
    await inspectWith("Enter");
    // Escape closes it and returns focus to the chip.
    await owners(page).press("Escape");
    await expect(owners(page)).toHaveCount(0);
    await expect(crab).toHaveAttribute("aria-expanded", "false");
    await expect(crab).toBeFocused();
    await inspectWith("Space");
    await owners(page).getByTestId("reaction-apply").click();
    await expect(owners(page)).toHaveCount(0);
    await expect(crab).toBeFocused();
    await expect(count(crab)).toHaveText("2");
    await crab.press("Enter");
    await expect(owners(page).getByTestId("reaction-remove")).toBeVisible();
    await expect(owners(page).getByTestId("reaction-owner")).toHaveText(["Test Sender B", "You"]);
    await owners(page).getByTestId("reaction-remove").click();
    await expect(count(crab)).toHaveText("1");

    await pick(page, row, "👍");
    await activateWithoutPointer(crab);
    await expect(owners(page).getByTestId("reaction-apply")).toHaveText("Switch to 🦀");
    await owners(page).getByTestId("reaction-apply").click();
    await expect(chip(row, "👍")).toHaveCount(0);
    await expect(crab).toHaveAttribute("aria-pressed", "true");
    await expect(count(crab)).toHaveText("2");
  });

  // A click with no press of its own (assistive technology, or a script)
  // follows each ending, and no key is pressed: the keyboard clears the press
  // record itself, which would hide an ending that did not.
  test("a press that was cancelled or left the chip cannot authorize a later click", async ({ page }) => {
    const row = await openRoomWithTarget(page);
    await callRiverTest(page, "memberReactsToNewest", "🦀");
    const crab = chip(row, "🦀");
    for (const ending of ["pointercancel", "pointerleave"]) {
      await mouseDownOnly(crab);
      await crab.dispatchEvent(ending, { pointerType: "mouse", pointerId: 1 });
      await activateWithoutPointer(crab);
      await expect(owners(page), `${ending}: the click inspects`).toHaveCount(1);
      await expect(owners(page)).toBeFocused();
      await expect(crab, `${ending}: the click does not react`).toHaveAttribute("aria-pressed", "false");
      await expect(count(crab)).toHaveText("1");
      await owners(page).press("Escape");
      await expect(owners(page)).toHaveCount(0);
    }
    // Premise: the same press with no ending does authorize that click, so
    // the endings above are what revoked it.
    await mouseDownOnly(crab);
    await activateWithoutPointer(crab);
    await expect(crab).toHaveAttribute("aria-pressed", "true");
    await expect(count(crab)).toHaveText("2");
    await expect(owners(page)).toHaveCount(0);
  });

  test("an abandoned pointer press never turns keyboard inspection into a toggle", async ({ page }) => {
    const row = await openRoomWithTarget(page);
    await callRiverTest(page, "memberReactsToNewest", "🦀");
    const crab = chip(row, "🦀");
    // The press is still on record when the key goes down. The one click
    // the native button sends for it inspects.
    for (const key of ["Enter", "Space"]) {
      await mouseDownOnly(crab);
      await crab.focus();
      await page.keyboard.press(key);
      await expect(owners(page), `${key}: one list`).toHaveCount(1);
      await expect(owners(page)).toBeFocused();
      await expect(crab, `${key}: inspection does not react`).toHaveAttribute("aria-pressed", "false");
      await expect(count(crab)).toHaveText("1");
      await owners(page).press("Escape");
      await expect(owners(page)).toHaveCount(0);
      await expect(crab).toBeFocused();
    }
  });

  // The window itself (PRESS_FRESH_MS, 1500) is pinned natively with an
  // injected clock; this is the one check that the click reads the browser's.
  test("an old mouse press cannot authorize a later click", { tag: "@chromium-only" }, async ({ page }) => {
    const row = await openRoomWithTarget(page);
    await callRiverTest(page, "memberReactsToNewest", "🦀");
    const crab = chip(row, "🦀");
    await mouseDownOnly(crab);
    await page.waitForTimeout(1600);
    await activateWithoutPointer(crab);
    await expect(owners(page)).toBeVisible();
    await expect(crab).toHaveAttribute("aria-pressed", "false");
    await expect(count(crab)).toHaveText("1");
  });

  test("switching reactor lists across message groups keeps only the newest dialog focused", async ({ page }) => {
    await openRoomWithComposer(page);
    await callRiverTest(page, "deliverTimedMessages", 0, [{ text: "owners first group", sentSecs: -2, receivedSecs: 0 }]);
    await callRiverTest(page, "memberReactsToNewest", "🦀");
    const first = chip(committedRow(page, "owners first group"), "🦀");
    await expect(first).toHaveCount(1);
    await callRiverTest(page, "deliverTimedMessages", 1, [{ text: "owners second group", sentSecs: -1, receivedSecs: 0 }]);
    await callRiverTest(page, "memberReactsToNewest", "❤️");
    const second = chip(committedRow(page, "owners second group"), "❤️");
    await expect(second).toHaveCount(1);
    const [firstId, secondId] = [await first.getAttribute("id"), await second.getAttribute("id")];
    await activateWithoutPointer(first);
    await expect(owners(page)).toBeFocused();
    await activateWithoutPointer(second);
    await expect(owners(page)).toHaveCount(1);
    await expect(owners(page)).toHaveAttribute("id", await second.getAttribute("aria-controls") as string);
    await settle(page);
    await expect(owners(page), "the old group's close effect cannot steal focus").toBeFocused();
    await owners(page).press("Escape");

    // Two queued openings before either focus task settles: the later target
    // wins, and a close callback from the first group is already obsolete.
    await page.evaluate(([a, b]) => {
      document.getElementById(a!)!.click();
      document.getElementById(b!)!.click();
    }, [firstId, secondId]);
    await expect(owners(page)).toHaveCount(1);
    await expect(owners(page)).toHaveAttribute("id", await second.getAttribute("aria-controls") as string);
    await settle(page);
    await expect(owners(page)).toBeFocused();
    await expect(first).toHaveAttribute("aria-expanded", "false");
    await expect(second).toHaveAttribute("aria-expanded", "true");
  });

  test("queued chip and list actions belong only to the room showing that opened them", { tag: "@chromium-only" }, async ({ page }) => {
    for (const back of [false, true]) for (const action of ["inspect", "mouse", "apply", "remove"]) {
      const row = await openRoomWithTarget(page);
      await callRiverTest(page, "memberReactsToNewest", "🦀");
      const crab = chip(row, "🦀");
      await expect(crab).toHaveCount(1);
      if (action === "remove") {
        await crab.click();
        await expect(crab).toHaveAttribute("aria-pressed", "true");
      }
      if (action === "apply" || action === "remove") {
        await crab.press("Enter");
        await expect(owners(page)).toBeFocused();
      }
      const selected = action === "remove";
      const selector = action === "apply" || selected
        ? `[data-testid="reaction-${selected ? "remove" : "apply"}"]`
        : `[id="${await crab.getAttribute("id")}"]`;
      const signs = await callRiverTest(page, "messageSignsRecorded");
      await page.evaluate(({ selector, action, back }) => {
        const hooks = (window as unknown as { __riverTest: { switchRoom(name: string): void } }).__riverTest;
        const target = document.querySelector<HTMLElement>(selector)!;
        if (action === "mouse") target.dispatchEvent(new PointerEvent("pointerdown", { pointerType: "mouse", pointerId: 1, isPrimary: true, button: 0, bubbles: true }));
        hooks.switchRoom("Team Chat Room");
        if (back) hooks.switchRoom("Your Private Room");
        target.click();
      }, { selector, action, back });
      if (!back) {
        await expect(page.getByRole("heading", { name: "Team Chat Room" })).toBeVisible();
        await expect(owners(page)).toHaveCount(0);
        await callRiverTest(page, "switchRoom", "Your Private Room");
      }
      await expect(row).toHaveCount(1);
      await settle(page);
      await expect(owners(page), `${action}: no list survives an earlier showing`).toHaveCount(0);
      await expect(crab, `${action}: the earlier showing cannot change the reaction`).toHaveAttribute("aria-pressed", String(selected));
      await expect(count(crab)).toHaveText(selected ? "2" : "1");
      expect(await callRiverTest(page, "messageSignsRecorded"), `${action}: nothing was signed after the switch${back ? " away and back" : ""}`).toBe(signs);
    }
  });

  test("a pen follows the screen's pointer capability, not the click's claimed type", async ({ page }) => {
    const row = await openRoomWithTarget(page);
    await callRiverTest(page, "memberReactsToNewest", "🦀");
    const crab = chip(row, "🦀");
    const fine = await page.evaluate(() => matchMedia("(pointer: fine)").matches);
    await crab.dispatchEvent("pointerdown", { pointerType: "pen", pointerId: 2, isPrimary: true, button: 0 });
    await crab.dispatchEvent("pointerup", { pointerType: "pen", pointerId: 2, isPrimary: true, button: 0 });
    // A MouseEvent click has no pointerType to claim; this one is a
    // PointerEvent that says "mouse" after a pen's press.
    const claimed = await crab.evaluate((el) => {
      const click = new PointerEvent("click", {
        pointerType: "mouse", pointerId: 2, isPrimary: true, button: 0, bubbles: true, cancelable: true, composed: true,
      });
      el.dispatchEvent(click);
      return click.pointerType;
    });
    expect(claimed, "premise: the click claims a mouse").toBe("mouse");
    await expect(crab).toHaveAttribute("aria-pressed", String(fine));
    await expect(count(crab)).toHaveText(fine ? "2" : "1");
    if (fine) await expect(owners(page)).toHaveCount(0);
    else await expect(owners(page)).toBeVisible();
  });

  // Order is computed in Rust from the signed actions, the same in every
  // engine: once, through the real handlers and the DOM.
  test("standing order appends an alphabetically earlier emoji and moves a removed then re-added interval", { tag: "@chromium-only" }, async ({ page }) => {
    const row = await openRoomWithTarget(page);
    await callRiverTest(page, "memberReactsToNewest", "🦀");
    await pick(page, row, "🔥");
    await callRiverTest(page, "memberReactsToNewest", "❤️");
    await expect.poll(() => order(row)).toEqual(["🦀", "🔥", "❤️"]);
    await chip(row, "🔥").click();
    await expect.poll(() => order(row)).toEqual(["🦀", "❤️"]);
    await pick(page, row, "🔥");
    await expect.poll(() => order(row)).toEqual(["🦀", "❤️", "🔥"]);
    // Joining and leaving the older emoji preserves the other member's interval.
    await chip(row, "🦀").click();
    await expect.poll(() => order(row)).toEqual(["🦀", "❤️"]);
    await expect(count(chip(row, "🦀"))).toHaveText("2");
    await chip(row, "🦀").click();
    await expect.poll(() => order(row)).toEqual(["🦀", "❤️"]);
    await expect(count(chip(row, "🦀"))).toHaveText("1");
  });
});

// A received row's dense footer. An own row's is "Footer at 320px" in
// message-action-buttons.spec.ts, held to the same shared geometry checks.
test("dense received chips wrap inside a 320px footer, and React reaches the row's actions", async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 760 });
  const row = await openRoomWithTarget(page);
  const emojis = ["🦀", "❤️", "👍", "🎉", "🔥", "👀", "🚀", "💯", "😀", "🙌", "✅", "🤔"];
  await callRiverTest(page, "addReactionsToNewest", emojis);
  await expect(chips(row)).toHaveCount(emojis.length);
  await row.evaluate((el) => el.scrollIntoView({ block: "center" }));
  await settle(page);
  const layout = await footerLayout(row);
  expect(layout.left.map((c) => c.id), "every chip, then the one React").toEqual([
    ...Array(emojis.length).fill("reaction-chip"), "message-react-button",
  ]);
  const lines = new Set(layout.left.slice(0, -1).map((c) => Math.round(c.box.top)));
  expect(lines.size, "premise: the chips wrap").toBeGreaterThan(1);
  expect(
    layout.cluster.filter((c) => c.box.width > 0 || c.box.height > 0),
    "no trailing cluster below 48rem",
  ).toEqual([]);
  expectUsableLeftGroup(layout, "received");
  expectClear(layout.left, layout, "received");
  expect(
    await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth),
    "the page does not overflow sideways",
  ).toBe(true);
  // Reply is not in this footer. It is one press away: React opens the one
  // message sheet for this row, which holds the reactions and Reply.
  await openSheetFromReact(page, row);
  await expect(palette(page)).toBeVisible();
  await expect(page.getByTestId("mobile-message-action-reply")).toBeVisible();
});

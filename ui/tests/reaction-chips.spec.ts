    await expect(crab).toHaveAttribute("data-own-reaction", String(fine));
    await expect(count(crab)).toHaveText(fine ? "2" : "1");
    if (fine) await expect(owners(page)).toHaveCount(0);
    else await expect(owners(page)).toBeVisible();

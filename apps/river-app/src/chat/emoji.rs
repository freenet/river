#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_list_matches_the_web_ui() {
        let web = include_str!("../../../../ui/src/components/conversation/emoji_picker.rs")
            .replace("\r\n", "\n");
        let mine = include_str!("emoji.rs").replace("\r\n", "\n");
        let list = |s: &str, from: &str, to: &str| {
            let a = s.find(from).expect("list start");
            let b = s[a..].find(to).map_or(s.len(), |i| a + i);
            s[a..b].trim_end().to_owned()
        };
        let web_list = list(&web, "pub const EMOJI_CATEGORIES", "/// Common/frequently");
        let mine_list = list(&mine, "pub const EMOJI_CATEGORIES", "\n#[cfg(test)]");
        assert_eq!(web_list.replace("#[allow(dead_code)]\n", ""), mine_list);
        assert!(EMOJI_CATEGORIES.len() >= 5);
    }
}
